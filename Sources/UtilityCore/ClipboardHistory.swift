import AppKit
import ImageIO
import Observation
import UniformTypeIdentifiers

@MainActor
package enum ConcealedClipboard {
    fileprivate static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    fileprivate static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")

    @discardableResult
    package static func write(_ item: NSPasteboardItem, to board: NSPasteboard = .general) -> Bool {
        guard item.setData(Data(), forType: concealed), item.setData(Data(), forType: transient) else {
            return false
        }
        board.clearContents()
        return board.writeObjects([item])
    }
}

@MainActor
@Observable
package final class ClipboardHistoryController {
    package enum Status { case disabled, recording, paused }

    package struct Entry: Identifiable {
        package enum Content: Equatable {
            case text(String)
            case image(Data, NSPasteboard.PasteboardType)

            package static func == (lhs: Self, rhs: Self) -> Bool {
                switch (lhs, rhs) {
                case let (.text(left), .text(right)):
                    left.utf8.elementsEqual(right.utf8)
                case let (.image(left, leftType), .image(right, rightType)):
                    leftType == rightType && left == right
                default:
                    false
                }
            }

            var byteCount: Int {
                switch self {
                case .text(let text): text.utf8.count
                case .image(let data, _): data.count
                }
            }
        }

        package let id = UUID()
        package let content: Content
        package fileprivate(set) var date = Date()
        package let foregroundApp: String?
        package var pinned = false
    }

    package private(set) var status: Status = .disabled
    package private(set) var entries: [Entry] = []
    package private(set) var excludedApps: Set<String> = []
    package var retention = 25 {
        didSet { trimHistory() }
    }

    private let pasteboard: () -> NSPasteboard
    private let foregroundApp: () -> (id: String?, name: String?)
    @ObservationIgnored private var monitor: Task<Void, Never>?
    @ObservationIgnored private var lastChange = 0
    @ObservationIgnored private var previousApp: String?

    // Maccy uses changeCount polling and these de facto pasteboard marker types.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        ConcealedClipboard.concealed,
        ConcealedClipboard.transient,
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init(UTType.jpeg.identifier), .init(UTType.gif.identifier)]
    private static let declaredSource = NSPasteboard.PasteboardType("org.nspasteboard.source")

    package init(
        pasteboard: @escaping () -> NSPasteboard = { .general },
        foregroundApp: @escaping () -> (id: String?, name: String?) = {
            let app = NSWorkspace.shared.frontmostApplication
            return (app?.bundleIdentifier, app?.localizedName)
        }
    ) {
        self.pasteboard = pasteboard
        self.foregroundApp = foregroundApp
    }

    deinit { monitor?.cancel() }

    package func start() {
        guard status != .recording else { return }
        lastChange = pasteboard().changeCount
        previousApp = foregroundApp().id
        status = .recording
        monitor = Task { [weak self] in
            while !Task.isCancelled {
                do { try await Task.sleep(for: .milliseconds(300)) }
                catch { return }
                self?.poll()
            }
        }
    }

    package func pause() { stop(as: .paused) }
    package func disable() { stop(as: .disabled) }

    private func stop(as newStatus: Status) {
        monitor?.cancel()
        monitor = nil
        status = newStatus
    }

    package func exclude(_ bundleIdentifier: String) {
        let identifier = bundleIdentifier.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if !identifier.isEmpty { excludedApps.insert(identifier) }
    }

    package func allow(_ bundleIdentifier: String) { excludedApps.remove(bundleIdentifier) }

    package func poll() {
        guard status == .recording else { return }
        let board = pasteboard()
        let app = foregroundApp()
        let change = board.changeCount
        defer { previousApp = app.id }
        guard lastChange != change else { return }
        lastChange = change
        guard let appID = app.id, appID == previousApp,
              !excludedApps.contains(appID.lowercased()),
              let items = board.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }),
              !items.contains(where: hasExcludedSource)
        else { return }

        let captured = items.prefix(25).compactMap { item in
            Self.content(for: item).map { Entry(content: $0, foregroundApp: app.name) }
        }
        // A different process can replace the clipboard while AppKit loads its data.
        guard board.changeCount == change, foregroundApp().id == appID else { return }
        for entry in captured.reversed() {
            if let index = entries.firstIndex(where: { $0.content == entry.content }) {
                var existing = entries.remove(at: index)
                existing.date = entry.date
                entries.insert(existing, at: 0)
            } else {
                entries.insert(entry, at: 0)
            }
        }
        trimHistory()
    }

    private func hasExcludedSource(_ item: NSPasteboardItem) -> Bool {
        guard item.types.contains(Self.declaredSource), let source = item.string(forType: Self.declaredSource) else { return false }
        // A declared source supplements the foreground-app check. It cannot override it.
        return excludedApps.contains(source.trimmingCharacters(in: .whitespacesAndNewlines).lowercased())
    }

    @discardableResult
    package func copy(_ entry: Entry) -> Bool {
        let item = NSPasteboardItem()
        let ready: Bool
        switch entry.content {
        case .text(let text): ready = item.setString(text, forType: .string)
        case .image(let data, let type): ready = item.setData(data, forType: type)
        }
        guard ready else { return false }
        item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType"))
        let board = pasteboard()
        board.clearContents()
        let copied = board.writeObjects([item])
        lastChange = board.changeCount
        return copied
    }

    package func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        guard entries[index].pinned || entries.filter(\.pinned).count < 20 else { return }
        entries[index].pinned.toggle()
        trimHistory()
    }

    package func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
    package func clearUnpinned() { entries.removeAll { !$0.pinned } }

    private func trimHistory() {
        var slots = max(0, retention)
        var bytes = 64_000_000 - entries.filter(\.pinned).reduce(0) { $0 + $1.content.byteCount }
        entries = entries.filter { entry in
            if entry.pinned { return true }
            guard slots > 0, entry.content.byteCount <= bytes else { return false }
            slots -= 1
            bytes -= entry.content.byteCount
            return true
        }
    }

    private static func content(for item: NSPasteboardItem) -> Entry.Content? {
        guard !item.types.contains(.fileURL) else { return nil }
        for type in imageTypes where item.types.contains(type) {
            if let data = item.data(forType: type),
               (1...8_000_000).contains(data.count),
               let source = CGImageSourceCreateWithData(data as CFData, nil),
               let identifier = CGImageSourceGetType(source), identifier as String == type.rawValue,
               let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
               let width = properties[kCGImagePropertyPixelWidth] as? Int,
               let height = properties[kCGImagePropertyPixelHeight] as? Int,
               (1...8192).contains(width), (1...8192).contains(height) {
                return .image(data, type)
            }
        }
        guard item.types.contains(.string), let text = item.string(forType: .string),
              (1...1_000_000).contains(text.utf8.count)
        else { return nil }
        return .text(text)
    }
}
