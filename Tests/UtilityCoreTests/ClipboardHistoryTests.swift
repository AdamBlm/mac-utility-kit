import AppKit
import ImageIO
import Testing
import UniformTypeIdentifiers
@testable import UtilityCore

@MainActor
struct ClipboardHistoryTests {
    @Test func recordsOnlyNewUnmarkedChangesDuringOptInAndSkipsOwnCopy() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        write("before start", on: board)
        history.poll()
        history.start()
        history.poll()
        #expect(history.entries.isEmpty)

        for marker in ["ConcealedType", "TransientType", "AutoGeneratedType"] {
            write("sensitive", marker: marker, on: board)
            history.poll()
            #expect(history.entries.isEmpty)
        }

        write("ordinary", on: board)
        history.poll()
        let entry = try #require(history.entries.first)
        #expect(entry.content == .text("ordinary"))
        #expect(history.copy(entry))
        history.poll()
        #expect(history.entries.count == 1)
        #expect(board.string(forType: .string) == "ordinary")

        history.pause()
        write("paused", on: board)
        history.poll()
        history.start()
        history.poll()
        #expect(history.entries.count == 1)
        history.disable()
        write("disabled", on: board)
        history.poll()
        #expect(history.entries.count == 1)
    }

    @Test func honorsExclusionsAndPreservesPinnedEntriesAcrossTrimming() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        history.exclude("EXAMPLE.APP")
        history.start()
        defer { history.disable() }
        write("excluded", on: board)
        history.poll()
        #expect(history.entries.isEmpty)
        history.allow("example.app")
        write("pinned", on: board)
        history.poll()
        let entry = try #require(history.entries.first)
        history.togglePin(entry.id)
        history.retention = 1
        write("old", on: board)
        history.poll()
        write("recent", on: board)
        history.poll()
        #expect(history.entries.map(\.content) == [.text("recent"), .text("pinned")])
        history.clearUnpinned()
        #expect(history.entries.map(\.id) == [entry.id])
        history.remove(entry.id)
        #expect(history.entries.isEmpty)
    }

    @Test func declaredSourceCanExcludeButCannotOverrideForegroundExclusion() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.foreground", "Example") })
        history.start()
        defer { history.disable() }
        history.exclude("example.background")

        let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
        let hidden = NSPasteboardItem()
        hidden.setString("background fixture", forType: .string)
        hidden.setString("Example.Background", forType: sourceType)
        let regular = NSPasteboardItem()
        regular.setString("ordinary fixture", forType: .string)
        board.clearContents()
        #expect(board.writeObjects([regular, hidden]))
        history.poll()
        #expect(history.entries.isEmpty)

        history.exclude("example.foreground")
        let markedAllowed = NSPasteboardItem()
        markedAllowed.setString("foreground fixture", forType: .string)
        markedAllowed.setString("example.allowed", forType: sourceType)
        board.clearContents()
        #expect(board.writeObjects([markedAllowed]))
        history.poll()
        #expect(history.entries.isEmpty)

        history.allow("example.foreground")
        write("permitted fixture", on: board)
        history.poll()
        #expect(history.entries.map(\.content) == [.text("permitted fixture")])
    }

    @Test func recopyRefreshesRetentionOrderWithoutLosingIdentityOrPin() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        history.retention = 2
        history.start()
        defer { history.disable() }

        write("first", on: board)
        history.poll()
        let first = try #require(history.entries.first)
        for text in ["second", "first", "third"] {
            write(text, on: board)
            history.poll()
        }
        #expect(history.entries.map(\.content) == [.text("third"), .text("first")])
        #expect(history.entries.last?.id == first.id)

        history.togglePin(first.id)
        write("first", on: board)
        history.poll()
        #expect(history.entries.map(\.content) == [.text("first"), .text("third")])
        #expect(history.entries.first?.id == first.id)
        #expect(history.entries.first?.pinned == true)
    }

    @Test func recordsAndRestoresOnlyTheSelectedImageRepresentation() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        history.start()
        defer { history.disable() }
        let png = try #require(Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aVUkAAAAASUVORK5CYII="))
        let image = NSPasteboardItem()
        image.setData(png, forType: .png)
        image.setString("fallback", forType: .string)
        let text = NSPasteboardItem()
        text.setString("separate item", forType: .string)
        board.clearContents()
        #expect(board.writeObjects([image, text]))
        history.poll()
        #expect(history.entries.map(\.content) == [.image(png, .png), .text("separate item")])
        let entry = try #require(history.entries.first)
        #expect(history.copy(entry))
        #expect(board.pasteboardItems?.count == 1)
        #expect(board.data(forType: .png) == png)
        #expect(board.string(forType: .string) == nil)
    }

    @Test(arguments: [UTType.jpeg, .gif])
    func recordsOriginalImageBytesFromJPEGAndGIFRepresentations(format: UTType) throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        history.start()
        defer { history.disable() }
        let image = try QRTools.generate(.text("fixture"))
        let bytes = NSMutableData()
        let destination = try #require(CGImageDestinationCreateWithData(bytes, format.identifier as CFString, 1, nil))
        CGImageDestinationAddImage(destination, image, nil)
        try #require(CGImageDestinationFinalize(destination))
        let data = bytes as Data
        let type = NSPasteboard.PasteboardType(format.identifier)

        let item = NSPasteboardItem()
        item.setData(data, forType: .png) // The declared format does not match these bytes.
        item.setData(data, forType: type)
        item.setString("fallback", forType: .string)
        board.clearContents()
        #expect(board.writeObjects([item]))
        history.poll()
        let entry = try #require(history.entries.first)
        #expect(entry.content == .image(data, type))
        #expect(history.copy(entry))
        #expect(board.data(forType: type) == data)
        #expect(board.data(forType: .png) == nil)
        #expect(board.string(forType: .string) == nil)
    }

    @Test func concealedWiFiQRRemainsPasteableAndIsSkippedByHistory() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let history = ClipboardHistoryController(pasteboard: { board }, foregroundApp: { ("example.app", "Example") })
        history.start()
        defer { history.disable() }

        let payload = "WIFI:T:WPA;S:Example;P:example-password;;"
        #expect(QRTools.isWiFiPayload(payload))
        #expect(QRTools.isWiFiPayload("\u{FEFF}" + payload))
        #expect(!QRTools.isWiFiPayload("https://example.com"))
        let item = NSPasteboardItem()
        let png = try #require(Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aVUkAAAAASUVORK5CYII="))
        item.setString(payload, forType: .string)
        item.setData(png, forType: .png)
        #expect(ConcealedClipboard.write(item, to: board))
        history.poll()
        #expect(history.entries.isEmpty)
        #expect(board.string(forType: .string) == payload)
        #expect(board.data(forType: .png) == png)
    }

    private func write(_ text: String, marker: String? = nil, on board: NSPasteboard) {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if let marker { item.setData(Data(), forType: .init("org.nspasteboard." + marker)) }
        board.clearContents()
        board.writeObjects([item])
    }
}
